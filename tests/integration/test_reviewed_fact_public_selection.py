@pytest.mark.parametrize("selected", [False, True])
def test_completed_original_intent_replays_after_source_review_changes_without_new_fact_audit(
        tmp_path, selected):
    with _current(tmp_path) as chain:
        body = _body(chain) if selected else _command(chain).model_dump(mode="json", by_alias=True)
        first = _post(chain, body, key="frozen-replay")
        assert first.status_code == 200, first.text
        identity = first.json()["id"]
        with chain.plans._unit_of_work() as work:
            original = work.daily.get(identity)
            store = SourceCoverageStore(work.daily.session)
            old = store.latest(chain.version["id"])
            store.append(chain.version["id"], old.assessment, inputs=old.inputs,
                expected_revision=old.revision, command_id="unreviewed-after-receipt",
                now=chain.now)
            work.commit()

        def fact_audits():
            with chain.plans._unit_of_work() as work:
                audits = work.daily.session.execute(select(AuditLog.__table__).where(
                    AuditLog.entity_id == identity).order_by(AuditLog.id))
                return work.daily.get(identity), tuple(tuple(row) for row in audits)

        before = fact_audits()
        assert before[0] == original
        replay = _post(chain, body, key="frozen-replay")
        assert replay.status_code == 200 and replay.content == first.content
        assert fact_audits() == before
        # A fresh intent still must pass today's actual source/review gate.
        fresh = _post(chain, {**_body(chain), "factId": "fresh-after-source-change"}, key="fresh")
        # Preserve the existing FACT service's sanitized semantic rejection.
        assert fresh.status_code == 422, fresh.text


@pytest.mark.parametrize("damage", ["erase", "move", "upgrade-unbound", "upgrade-no-observation"])
def test_public_fresh_intent_cannot_erase_move_or_upgrade_existing_fact_binding(tmp_path, damage):
    with _current(tmp_path) as chain:
        body = _body(chain)
        original = deepcopy(body)
        if damage == "upgrade-unbound":
            original.pop("conditionSelection")
        first = _post(chain, original)
        assert first.status_code == 200, first.text
        revision = first.json()["revision"]
        if damage == "upgrade-no-observation":
            with chain.plans._unit_of_work() as work:
                row = work.daily.get(first.json()["id"])
                payload = deepcopy(row["payload"])
                payload.pop("reviewed_fact_observation")
                saved = work.daily.save(row["id"], kind="FACT", symbol=chain.plan.symbol,
                    lineage=row["lineage"], expected_revision=row["revision"], payload=payload)
                work.commit()
                revision = saved["revision"]
        body["expectedRevision"] = revision
        if damage == "erase":
            body.pop("conditionSelection")
        elif damage == "move":
            body["conditionSelection"] = _selection(1)
        before = _snapshot(chain)
        rejected = _post(chain, body, key="fresh-binding-change")
        assert rejected.status_code == 422, rejected.text
        assert _snapshot(chain) == before


