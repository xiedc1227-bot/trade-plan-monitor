def test_omitted_selector_preserves_independent_old_json_dump_and_request_preimage():
    frozen = json.loads(LEGACY_JSON)
    command = DailyFactCommand.model_validate(frozen)
    assert command.model_dump_json(by_alias=True) == LEGACY_JSON
    assert command.model_dump(mode="json", by_alias=True) == frozen
    names = dict(planVersionId="plan_version_id", contentHash="content_hash", factId="fact_id",
        kind="kind", tradeDate="trade_date", signalId="signal_id", evidence="evidence",
        satisfied="satisfied", officialEvidence="official_evidence",
        expectedRevision="expected_revision")
    plain = {names[name]: value for name, value in frozen.items()}
    assert command.model_dump(mode="json") == plain
    assert command.model_dump() == {**plain, "plan_version_id": UUID(plain["plan_version_id"]),
                                   "trade_date": date.fromisoformat(plain["trade_date"])}
    assert command.model_dump_json() == json.dumps(plain, separators=(",", ":"))
    preimage = json.dumps(dict(command=frozen, operation="DAILY_FACT"), ensure_ascii=False,
                         separators=(",", ":"), sort_keys=True).encode("utf-8")
    assert len(preimage) == 397
    assert sha256(preimage).hexdigest() == LEGACY_REQUEST_HASH
    assert operation_hash("DAILY_FACT", command) == LEGACY_REQUEST_HASH
    assert command.model_copy(update={"evidence": plain["evidence"]}).model_dump(
        mode="json", by_alias=True) == frozen


