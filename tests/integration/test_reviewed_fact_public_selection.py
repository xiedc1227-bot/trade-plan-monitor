@pytest.mark.parametrize("change", ["bar", "source", "same-content-receipt"])
def test_public_observation_binding_tracks_actual_period_and_source_content(tmp_path, change):
    with _current(tmp_path) as chain:
        original = minute_inputs(chain)
        persist_minute_inputs(chain, original)
        body = _body(chain)
        first = _post(chain, body)
        assert first.status_code == 200, first.text
        chain.now += timedelta(minutes=5) if change == "bar" else timedelta(seconds=1)
        current = _minute_at_current_clock(chain, original)
        if change == "source":
            minutes = list(current.minute_prefix)
            minutes[1] = minutes[1].model_copy(update={"close_fen": 3969})
            current = current.model_copy(update={"minute_prefix": tuple(minutes)})
            assert current.five_minute_bars == original.five_minute_bars
        persist_minute_inputs(chain, current)
        chain.runtime.run_inputs(plan=chain.plan, inputs=current)
        before = _snapshot(chain)
        revised = _post(chain, {**body, "expectedRevision": 1}, key="observed-revision")
        if change == "same-content-receipt":
            assert revised.status_code == 200 and revised.json()["revision"] == 2
        else:
            assert revised.status_code == 422, revised.text
            assert _snapshot(chain) == before
            fresh = _post(chain, {**body, "factId": "fresh-observation"}, key="fresh-observation")
            assert fresh.status_code == 200, fresh.text


