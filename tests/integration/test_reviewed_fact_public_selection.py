@contextmanager
def _profile(chain, version):
    if version == 1:
        assert chain.app.state.monitor_contract_version == 1
        yield chain.client
        return
    # Real v2 service on the same temporary SQL. No runtime-read authority is
    # available or granted here; writes use the actual existing plan service.
    reads = RuntimeStatusReadService(chain.plans._require_session_factory(), lambda: None,
                                    clock=lambda: chain.now)
    app = create_app(monitor_contract_version=2, read_service=reads,
        plan_service=chain.plans.operation_service, runtime_factory=lambda: OfflineRuntime(chain))
    assert app.state.monitor_contract_version == 2
    with TestClient(app, base_url="http://127.0.0.1:8765") as client:
        yield client


def _selection(index=0):
    return dict(ownerKind="ORDINARY_RULE", ownerId="low-buy",
                conditionPath=f"condition.conditions[{index}]")


def _post(chain, body, *, key="public-fact", client=None, profile=1):
    headers = {"Idempotency-Key": key}
    if profile == 2:
        headers["X-Monitor-Contract-Version"] = "2"
    def forbidden(*args, **kwargs):
        pytest.fail("public FACT request attempted network acquisition")

    with pytest.MonkeyPatch.context() as offline:
        # Preserve the socket class: Windows asyncio uses it in internal type
        # checks while scheduling ASGI work. Block outbound connections instead.
        offline.setattr("socket.socket.connect", forbidden)
        offline.setattr("socket.socket.connect_ex", forbidden)
        offline.setattr("socket.create_connection", forbidden)
        return (client or chain.client).post("/api/v1/plan-facts", json=body, headers=headers)


def _body(chain, index=0, **changes):
    return {**_command(chain, **changes).model_dump(mode="json", by_alias=True),
            "conditionSelection": _selection(index)}


